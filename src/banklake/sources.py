"""The three fictional source systems: persistent SQLite databases, and the load-frequency rules.

Each source system has its own database file under data/sources/. They are seeded ONCE (from the project's
synthetic data generator) and never regenerated by an ingestion run. Every table carries a `business_date`
column: the date the record belongs to. Which tables are loaded on a given business date comes from the
`source_tables` metadata (load frequency) and `due_loads()` below.
"""
import os
import shutil
import sqlite3
import tempfile
from dataclasses import dataclass
from datetime import date, datetime, timedelta
from pathlib import Path

import numpy as np
import pandas as pd

from . import meta
from .common import DATA
from .schemas import CALENDAR, ENTITIES, SOURCES, source_columns

SOURCE_DIR = DATA / "sources"
FREQUENCIES = ("DAILY", "MONTHLY", "QUARTERLY")


def db_path(source_id: str) -> Path:
    return SOURCE_DIR / SOURCES[source_id]["db"]


def connect(source_id: str) -> sqlite3.Connection:
    return sqlite3.connect(f"file:{db_path(source_id)}?mode=ro", uri=True, timeout=30)


SEED_VERSION = 3   # bump when the source tables change: the databases are rebuilt (and Bronze loads of them reset) once


def sources_ready() -> bool:
    for sid in SOURCES:
        p = db_path(sid)
        if not p.exists():
            return False
        c = sqlite3.connect(p)
        v = c.execute("PRAGMA user_version").fetchone()[0]
        c.close()
        if v != SEED_VERSION:
            return False
    return True


def _reset_loads():
    """After the source databases are rebuilt, earlier loads no longer describe them: forget them and remove those Bronze files."""
    try:
        if not meta.query("SELECT 1 FROM ingestion_batches LIMIT 1"):
            return
    except Exception:   # noqa: BLE001 - metadata tables not created yet: nothing was loaded
        return
    from .common import layer_path
    for r in meta.query("SELECT DISTINCT entity FROM ingestion_batches"):
        shutil.rmtree(layer_path("bronze", r["entity"]), ignore_errors=True)
    meta.execute("DELETE FROM ingestion_batches")
    meta.execute("DELETE FROM ingestion_runs")


# ---------------------------------------------------------------- seeding (once)
def _read_raw(raw: Path, entity: str) -> pd.DataFrame:
    from . import datagen
    spec = ENTITIES[entity]
    files = sorted(p for p in (raw / entity).glob("*") if p.suffix in (".csv", ".json"))
    parts = []
    for f in files:
        if spec["fmt"] == "csv":
            parts.append(pd.read_csv(f, dtype=str, keep_default_na=False, na_values=[""]))
        else:
            parts.append(datagen.read_jsonl(f))
    df = pd.concat(parts, ignore_index=True)
    return df[[c for c in spec["columns"] if c in df.columns]]


def ensure_sources(scale: str | None = None, force: bool = False) -> bool:
    """Create the three source databases if they do not exist yet. Returns True when it created them.
    Existing databases are left exactly as they are, so the records are the same on every ingestion."""
    if sources_ready() and not force:
        return False
    from . import datagen, sourcegen
    scale = scale or os.environ.get("BANKLAKE_SOURCE_SCALE", "source")
    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix="banklake_seed_"))
    real_raw = datagen.RAW
    datagen.RAW = tmp          # generate into a scratch folder: data/raw (the file-based demo) is not touched
    try:
        datagen.generate_full(scale)
        base = {e: _read_raw(tmp, e) for e in ENTITIES}
        rng = np.random.default_rng(2026)
        sourcegen.extend_core(base, rng)
        tables = {**base, **sourcegen.source_only_tables(base, rng)}
        d0, d1 = pd.Timestamp(CALENDAR[0]), pd.Timestamp(CALENDAR[1])
        days = (d1 - d0).days + 1
        for i, (sid, sd) in enumerate(SOURCES.items()):
            target = db_path(sid)
            partial = target.with_suffix(".db.partial")
            partial.unlink(missing_ok=True)
            con = sqlite3.connect(partial)
            for j, entity in enumerate(sd["tables"]):
                df = tables[entity][source_columns(entity)].copy()
                r = np.random.default_rng(100 + 10 * i + j)
                df["source_system"] = sd["system"]
                if entity == "fx_rate":
                    df["business_date"] = df["rate_date"]
                else:   # cycle through every date, then shuffle: each business date gets records (n // days at least)
                    df["business_date"] = (d0 + pd.to_timedelta(r.permutation(np.arange(len(df)) % days), unit="D")).strftime("%Y-%m-%d")
                df.to_sql(entity, con, index=False, if_exists="replace", chunksize=5000)
                con.execute(f'CREATE INDEX idx_{entity}_bd ON "{entity}"(business_date)')
            con.execute(f"PRAGMA user_version={SEED_VERSION}")
            con.commit()
            con.close()
            partial.replace(target)
    finally:
        datagen.RAW = real_raw
        shutil.rmtree(tmp, ignore_errors=True)
    _reset_loads()
    return True


def latest_business_date() -> date:
    """The most recent business date that may be ingested: yesterday (today's business day is still open)."""
    return date.today() - timedelta(days=1)


def check_business_date(bd) -> date:
    d = parse_date(bd)
    if d > latest_business_date():
        raise ValueError(f"Ingestion is available only up to {latest_business_date():%d %b %Y} (yesterday). "
                         f"{d:%d %b %Y} is not available yet.")
    return d


# ---------------------------------------------------------------- what is due on a business date
@dataclass(frozen=True)
class Load:
    source_id: str
    source_name: str
    entity: str
    frequency: str
    period_key: str      # idempotency key, e.g. D:2026-07-01 or M:2026-06-30
    period_end: str      # the date whose records / closing snapshot is loaded
    snapshot: bool

    @property
    def label(self) -> str:
        return {"DAILY": "Daily", "MONTHLY": "Monthly", "QUARTERLY": "Quarterly"}[self.frequency]


def parse_date(d) -> date:
    if isinstance(d, datetime):
        return d.date()
    if isinstance(d, date):
        return d
    return datetime.strptime(str(d), "%Y-%m-%d").date()


def due_loads(business_date) -> list[Load]:
    """Tables to load for a business date, from each table's load frequency.
    DAILY    : the selected date.
    MONTHLY  : on the 1st of a month, the previous month's closing snapshot (period end = the day before).
    QUARTERLY: on the 1st of Jan/Apr/Jul/Oct, the previous quarter's closing snapshot."""
    bd = parse_date(business_date)
    prev_end = bd - timedelta(days=1)
    out = []
    for r in meta.query("SELECT t.source_id, s.name, t.entity, t.load_frequency FROM source_tables t "
                        "JOIN source_systems s USING(source_id) WHERE t.is_active='Y' ORDER BY t.source_id, t.rowid"):
        f = r["load_frequency"]
        if f == "DAILY":
            out.append(Load(r["source_id"], r["name"], r["entity"], f, f"D:{bd}", str(bd), False))
        elif f == "MONTHLY" and bd.day == 1:
            out.append(Load(r["source_id"], r["name"], r["entity"], f, f"M:{prev_end}", str(prev_end), True))
        elif f == "QUARTERLY" and bd.day == 1 and bd.month in (1, 4, 7, 10):
            out.append(Load(r["source_id"], r["name"], r["entity"], f, f"Q:{prev_end}", str(prev_end), True))
    return out


def configured_tables() -> list[dict]:
    return meta.query("SELECT t.source_id, s.name, t.entity, t.load_frequency FROM source_tables t "
                      "JOIN source_systems s USING(source_id) WHERE t.is_active='Y' ORDER BY t.source_id, t.rowid")


def where_clause(load: Load) -> tuple[str, tuple]:
    """Daily: the records of that date. Snapshot: every record up to and including the period end."""
    return ("business_date <= ?" if load.snapshot else "business_date = ?"), (load.period_end,)


def source_summary() -> list[dict]:
    """Real record count of every source table (for the page header)."""
    out = []
    for t in configured_tables():
        n = None
        if db_path(t["source_id"]).exists():
            con = connect(t["source_id"])
            n = con.execute(f'SELECT count(*) FROM "{t["entity"]}"').fetchone()[0]
            con.close()
        out.append({**t, "records": n})
    return out
