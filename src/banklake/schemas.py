# Columns every source file carries so that batches can be traced and changes (CDC) can be applied.
#   source_system = which fictional upstream system produced the row
#   batch_id      = 1 for the initial full load, 2, 3, ... for later incremental batches
#   op_type       = I (insert), U (update) or D (delete) - the change the row describes
CDC_COLUMNS = ["source_system", "batch_id", "op_type"]
SOURCE_SYSTEM = {"customer": "CORE_BANKING", "account": "CORE_BANKING", "branch": "CORE_BANKING",
                 "transaction": "PAYMENTS_HUB", "deposit": "TREASURY", "loan": "LOAN_ORIGINATION"}
for _e, _spec in ENTITIES.items():
    for _c in ("created_at", "updated_at"):
        if _c not in _spec["columns"]:
            _spec["columns"].append(_c)
    _spec["columns"] += CDC_COLUMNS

