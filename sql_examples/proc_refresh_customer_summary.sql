REPLACE PROCEDURE BANKING.REFRESH_CUSTOMER_SUMMARY (IN p_branch VARCHAR(10))
BEGIN
  DECLARE v_rows INTEGER DEFAULT 0;

  /* Step 1: empty the summary table */
  DELETE FROM BANKING.CUSTOMER_SUMMARY ALL;

  /* Step 2: rebuild it from the account table */
  INSERT INTO BANKING.CUSTOMER_SUMMARY (CUSTOMER_ID, ACCOUNT_COUNT, TOTAL_BALANCE)
  SEL CUSTOMER_ID, COUNT(*), ZEROIFNULL(SUM(BALANCE))
  FROM BANKING.ACCOUNT
  WHERE STATUS = 'ACTIVE'
  GROUP BY CUSTOMER_ID;

  SET v_rows = ACTIVITY_COUNT;

  /* Step 3: top 10 customers report */
  SEL TOP 10 CUSTOMER_ID, TOTAL_BALANCE
  FROM BANKING.CUSTOMER_SUMMARY
  ORDER BY TOTAL_BALANCE DESC;
END;
